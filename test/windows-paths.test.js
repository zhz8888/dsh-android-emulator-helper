import assert from 'node:assert/strict'
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { test } from 'node:test'
import { createRuntime } from '../lib/runtime.js'
import { readPropertiesValue, unescapePropertiesValue } from '../lib/util/properties.js'
import { androidAvdHome, androidEnv, androidUserHome, isSdkRoot, javaHomeInfo, sdkRoots } from '../lib/providers/sdk.js'

/**
 * Windows path recognition and reading tests.
 *
 * The plugin finds the Android SDK and a JDK on a machine that records neither
 * in an environment variable, and it launches the SDK's `.bat` tools through
 * `cmd.exe`, which reads a command line as text rather than as arguments.
 * Both are Windows behaviours, and both are easy to get subtly wrong in a way
 * that only shows up on a real machine — so the rules are pinned here.
 */

/** A scratch directory that is removed when the test ends. */
async function scratch(t) {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'dsh-windows-'))
  t.after(async () => {
    const { rm } = await import('node:fs/promises')
    await rm(dir, { recursive: true, force: true })
  })
  return dir
}

/**
 * A runtime with an explicit environment, as the tests need one.
 *
 * @param {object} [options] - the runtime's inputs.
 * @param {string} [options.cwd] - the session workspace.
 * @param {NodeJS.ProcessEnv} [options.env] - the environment to read.
 * @param {Record<string, string>} [options.settings] - the live settings.
 * @returns {object} the runtime.
 */
function runtime({ cwd, env = {}, settings = {} } = {}) {
  const config = {}
  for (const [key, value] of Object.entries(settings)) {
    config[key] = { get: () => value }
  }
  return createRuntime({ config, env, cwd: cwd ?? os.tmpdir() })
}

// ---------------------------------------------------------------------------
// The Java properties file the build writes and the build tools write
// ---------------------------------------------------------------------------

test('properties unescaping follows the JVM rules', () => {
  // A backslash before a character the format does not recognise is dropped,
  // which is why the natural spelling of a Windows path loses its separators.
  assert.equal(unescapePropertiesValue('C:\\Users\\x'), 'C:Usersx')
  assert.equal(unescapePropertiesValue('C\\:\\\\Users\\\\x'), 'C:\\Users\\x')
  assert.equal(unescapePropertiesValue('C:\\\\Users\\\\x'), 'C:\\Users\\x')
  assert.equal(unescapePropertiesValue('D:/Android/Sdk'), 'D:/Android/Sdk')
  assert.equal(unescapePropertiesValue('a\\tb'), 'a\tb')
  assert.equal(unescapePropertiesValue('a\\u0041b'), 'aAb')
})

test('a properties file yields its sdk.dir as a usable path', async (t) => {
  const dir = await scratch(t)
  const file = path.join(dir, 'local.properties')
  // Exactly what the Android Gradle Plugin writes on Windows.
  await writeFile(file, ['## This file is automatically generated.', 'sdk.dir=D\\:\\\\Android\\\\Sdk', ''].join('\n'))
  assert.equal(await readPropertiesValue(file, 'sdk.dir'), 'D:\\Android\\Sdk')
  assert.equal(await readPropertiesValue(file, 'missing'), undefined)
})

test('a properties file without the key yields nothing', async (t) => {
  const dir = await scratch(t)
  const file = path.join(dir, 'local.properties')
  await writeFile(file, 'other=value\n')
  assert.equal(await readPropertiesValue(file, 'sdk.dir'), undefined)
})

// ---------------------------------------------------------------------------
// Recognizing an SDK root
// ---------------------------------------------------------------------------

test('a directory with SDK packages is an SDK root and its parent is not', async (t) => {
  const dir = await scratch(t)
  const sdk = path.join(dir, 'Android', 'Sdk')
  await mkdir(path.join(sdk, 'platform-tools'), { recursive: true })
  assert.equal(await isSdkRoot(sdk), true)
  // The parent holds the SDK but is not the SDK: a scan that stopped at the
  // first directory it found would name it and then find no `platform-tools`.
  assert.equal(await isSdkRoot(path.join(dir, 'Android')), false)
  assert.equal(await isSdkRoot(dir), false)
})

test('the SDK a project records in local.properties is a candidate', async (t) => {
  const dir = await scratch(t)
  const sdk = path.join(dir, 'Android', 'Sdk')
  await mkdir(path.join(sdk, 'platform-tools'), { recursive: true })
  await writeFile(path.join(dir, 'local.properties'), `sdk.dir=${sdk.replaceAll('\\', '\\\\')}\n`)
  const rt = runtime({ cwd: dir, env: {} })
  const roots = await sdkRoots(rt)
  assert.ok(roots.includes(sdk), `expected ${sdk} among ${roots.join(', ')}`)
})

